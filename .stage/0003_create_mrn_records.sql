-- ---------------------------------------------------------------------------
-- Concord ChemTrack - MRN sheet records
-- ---------------------------------------------------------------------------
-- Backs the "MRN Input" module: ten sets per sheet, each holding the chemical
-- selected plus its Poly and ISO weights, filed under the ISO week the sheet
-- belongs to.
--
-- One row per filled set. BatchID groups all rows of one submission, so a
-- sheet can be read back together. created_at is stamped by the database at
-- insert time.
--
-- Apply via the Supabase SQL Editor, or:
--   supabase db push
-- ---------------------------------------------------------------------------

create table if not exists public."MRNRecords" (
  "RecordID"   bigint generated by default as identity primary key,
  "BatchID"    uuid not null,
  "SetIndex"   smallint not null check ("SetIndex" between 1 and 10),
  "Chemical"   text null,
  "Poly"       numeric(18,3) not null default 0 check ("Poly" >= 0),
  "ISO"        numeric(18,3) not null default 0 check ("ISO" >= 0),
  "week"       smallint not null check ("week" between 1 and 53),
  "created_at" timestamptz not null default now(),
  "CreatedBy"  text null
);

comment on table public."MRNRecords" is
  'One row per filled set of an MRN sheet. BatchID groups all sets of one submission.';

comment on column public."MRNRecords"."SetIndex" is
  'Position of the set in the sheet, 1 to 10.';

comment on column public."MRNRecords"."Chemical" is
  'Chemical selected for this set, or the no-chemical marker.';

comment on column public."MRNRecords"."Poly" is
  'Weight recorded in the Poly box for this set, in kg. Forced to 0 when no chemical is selected.';

comment on column public."MRNRecords"."ISO" is
  'Weight recorded in the ISO box for this set, in kg. Forced to 0 when no chemical is selected.';

comment on column public."MRNRecords"."week" is
  'ISO week number (1-53) the MRN sheet belongs to.';

comment on column public."MRNRecords"."created_at" is
  'Timestamp of the submission, stamped by the database.';

-- Index for fast lookup by batch.
create index if not exists idx_mrn_records_batchid
  on public."MRNRecords" ("BatchID");

-- Index for per-week reporting.
create index if not exists idx_mrn_records_week
  on public."MRNRecords" ("week");

-- RLS: authenticated users can insert and read.
alter table public."MRNRecords" enable row level security;

create policy "Authenticated users can insert MRN records"
  on public."MRNRecords"
  for insert
  to authenticated
  with check (true);

create policy "Authenticated users can view MRN records"
  on public."MRNRecords"
  for select
  to authenticated
  using (true);
