-- ---------------------------------------------------------------------------
-- Concord ChemTrack - `chemicals` reference table and `ChemicalLoadingRecords`
-- ---------------------------------------------------------------------------
-- The `chemicals` table assigns a stable integer ID to each chemical name used
-- in the Chemical Loading dropdown. `ChemicalLoadingRecords` stores one row per
-- loaded line (range + line), grouped by a per-session BatchID.
--
-- Apply via the Supabase SQL Editor, or:
--   supabase db push
--   supabase db execute --file supabase/migrations/0002_create_chemical_loading_records.sql
-- ---------------------------------------------------------------------------

-- Chemicals reference table - integer IDs mapped to chemical names.
create table if not exists public.chemicals (
  id          integer primary key generated by default as identity,
  name        text not null unique,
  created_at  timestamptz not null default now()
);

comment on table public.chemicals is
  'Reference catalogue of chemicals issuable on the production floor.';

-- RLS on chemicals: authenticated users can read, writes go through service role.
alter table public.chemicals enable row level security;

create policy "Authenticated users can view chemicals"
  on public.chemicals
  for select
  to authenticated
  using (true);

-- Chemical loading records - one row per line per loading session.
create table if not exists public."ChemicalLoadingRecords" (
  "RecordID"      bigint generated by default as identity primary key,
  "BatchID"       uuid not null,
  "RangeCode"     varchar(30) not null,
  "LineCode"      varchar(10) not null,
  "ChemicalID"    integer null references public.chemicals(id),
  "StartWeight"   numeric(18,3) null,
  "BeforeWeight"  numeric(18,3) null,
  "AfterWeight"   numeric(18,3) null,
  "EndWeight"     numeric(18,3) null,
  "CreatedAt"     timestamptz not null default now(),
  "CreatedBy"     text null
);

comment on table public."ChemicalLoadingRecords" is
  'One row per chemical loading line. BatchID groups all lines of one session.';

-- Index for fast lookup by batch.
create index if not exists idx_chemical_loading_records_batchid
  on public."ChemicalLoadingRecords" ("BatchID");

-- Index for fast lookup by range + line.
create index if not exists idx_chemical_loading_records_range_line
  on public."ChemicalLoadingRecords" ("RangeCode", "LineCode");

-- RLS on ChemicalLoadingRecords: authenticated users can insert and read.
alter table public."ChemicalLoadingRecords" enable row level security;

create policy "Authenticated users can insert loading records"
  on public."ChemicalLoadingRecords"
  for insert
  to authenticated
  with check (true);

create policy "Authenticated users can view loading records"
  on public."ChemicalLoadingRecords"
  for select
  to authenticated
  using (true);

-- ---------------------------------------------------------------------------
-- Seed the chemicals table with the names used by the Chemical Loading dropdown.
-- "No Chemical" is intentionally excluded - it maps to a NULL ChemicalID.
-- ---------------------------------------------------------------------------
insert into public.chemicals (name) values
  ('BASF Midsole'),
  ('Coim Midsole'),
  ('Coim Outsole'),
  ('Sample'),
  ('US BASF'),
  ('US Coim')
on conflict (name) do nothing;
